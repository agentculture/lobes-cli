"""Residents file (``residents.toml``): who the operator can reach, per member.

Every field is ``detected`` (a probe found it) or ``needs_you`` (missing).
Nothing is guessed, and a mesh name is never turned into an ssh target.
``gateway_key`` is a bool (present or not), never the key itself.
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path

DETECTED = "detected"
NEEDS_YOU = "needs_you"
FIELDS = ("ssh", "user", "port", "lobes_path", "gateway_key")
DEFAULT_NAME = "residents.toml"


@dataclass(frozen=True)
class Field:
    value: object
    state: str


@dataclass
class Residents:
    residents: dict = field(default_factory=dict)
    guests: dict = field(default_factory=dict)


def _entry(probe: dict | None, existing: dict | None = None) -> dict:
    probe = probe or {}
    out = {}
    for name in FIELDS:
        old = (existing or {}).get(name)
        if old is not None and old.value not in (None, ""):
            out[name] = old  # operator's value wins (h26)
            continue
        val = probe.get(name)
        if val is None or val == "":
            out[name] = Field(None, NEEDS_YOU)
        else:
            out[name] = Field(val, DETECTED)
    return out


def _verified(roster: dict) -> list[str]:
    return [m["name"] for m in roster.get("members", []) if m.get("verified")]


def generate(roster: dict, probes: dict) -> Residents:
    """Fresh file: every verified roster member is a resident."""
    return Residents({n: _entry(probes.get(n)) for n in _verified(roster)})


def regenerate(existing: Residents, roster: dict, probes: dict) -> Residents:
    """Re-detect; keep operator-set fields; verified members not in file are guests."""
    residents = {n: _entry(probes.get(n), e) for n, e in existing.residents.items()}
    guests = {n: _entry(probes.get(n)) for n in _verified(roster) if n not in residents}
    return Residents(residents, guests)


def _safe_path(base: Path | str, name: str) -> Path:
    base_p = Path(base).resolve()
    if Path(name).is_absolute() or ".." in Path(name).parts:
        raise ValueError(f"path escapes the deployment dir: {name}")
    target = (base_p / name).resolve()
    if base_p != target and base_p not in target.parents:
        raise ValueError(f"path escapes the deployment dir: {name}")
    return target


def _toml_val(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    s = str(v).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def _dump(res: Residents) -> str:
    lines = ['# generated by lobes from the mesh roster; fix lines marked "fix:"']
    for kind, group in (("resident", res.residents), ("guest", res.guests)):
        for name, entry in group.items():
            lines.append("")
            lines.append(
                f"[{kind}.{_toml_val(name) if not name.replace('-', '').replace('_', '').isalnum() else name}]"
            )
            needs = [f for f in FIELDS if entry[f].state == NEEDS_YOU]
            for f in FIELDS:
                if entry[f].state == DETECTED:
                    lines.append(f"{f} = {_toml_val(entry[f].value)}")
                else:
                    lines.append(f"# fix: {f} unknown")
            if needs:
                lines.append("needs_you = [" + ", ".join(_toml_val(n) for n in needs) + "]")
    return "\n".join(lines) + "\n"


def save(res: Residents, base: Path | str, name: str = DEFAULT_NAME) -> Path:
    path = _safe_path(base, name)
    path.write_text(_dump(res), encoding="utf-8")
    return path


def _parse(table: dict) -> dict:
    out = {}
    for n, raw in table.items():
        entry = {}
        for f in FIELDS:
            if f in raw:
                entry[f] = Field(raw[f], DETECTED)
            else:
                entry[f] = Field(None, NEEDS_YOU)
        out[n] = entry
    return out


def load(base: Path | str, name: str = DEFAULT_NAME) -> Residents:
    path = _safe_path(base, name)
    if not path.exists():
        return Residents()
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    return Residents(_parse(data.get("resident", {})), _parse(data.get("guest", {})))
